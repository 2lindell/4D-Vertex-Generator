"""Lines of extra symmetry from groups containing the octahedral swirl group (supergroup_lines_oct.json).

Besides its normalizer (normalizer_oct.py), a larger group H containing G can give a seed's polychoron more symmetry:
where an element h of H \\ G fixes the seed and the group K generated by G and h still has only the 48 points of G p
in its orbit, the polychoron is symmetric under K. The candidates are the library's groups that contain G (tubical
families n = 1..12 and the Coxeter rotation groups); for each, every h of H \\ G whose fixed great circle crosses the
domain is tested at a point of each arc inside the domain.

    SWIRL_GROUP=oct python supergroup_lines_oct.py
"""
from __future__ import annotations

import json
import os

import numpy as np

import domain as D
import normalizer_oct as nz
from four_d_vertex_generator.generation import group_elements
from four_d_vertex_generator.library import named_symmetry

OUT = "supergroup_lines_oct.json"
G = D.ELEMENTS
GK = {tuple(np.round(g, 6).ravel()) for g in G}


def closure(gens, limit=5000):
    out = {tuple(np.round(np.eye(4), 6).ravel()): np.eye(4)}
    frontier = [np.eye(4)]
    while frontier:
        nxt = []
        for a in frontier:
            for g in gens:
                b = g @ a
                k = tuple(np.round(b, 6).ravel())
                if k not in out:
                    out[k] = b
                    nxt.append(b)
                    if len(out) > limit:
                        return None
        frontier = nxt
    return np.stack(list(out.values()))


def orbit_size(K, p):
    O = []
    for q in K @ p:
        if not any(np.linalg.norm(q - u) < 1e-7 for u in O):
            O.append(q)
    return len(O)


def arcs(Fx):
    th = np.linspace(0, 2 * np.pi, 7201)
    X = np.cos(th)[:, None] * Fx[0] + np.sin(th)[:, None] * Fx[1]
    ok = nz.in_domain(nz.beta(X))
    out, cur = [], None
    for i, o in enumerate(ok):
        if o and cur is None:
            cur = i
        if not o and cur is not None:
            out.append((th[cur], th[i - 1])); cur = None
    if cur is not None:
        out.append((th[cur], th[-1]))
    return [(a, b) for a, b in out if b - a > 1e-6]


def main():
    fams = ["octahedral_dihedral", "octahedral_dihedral_index2_2n", "octahedral_dihedral_index6_6n",
            "octahedral_cyclic", "octahedral_cyclic_index2", "octahedral_dihedral_index2_4n"]
    names = [f"h4_tubical_{f}_{n}" for f in fams for n in range(1, 13)] + ["b4+", "d4+", "f4+", "h4+", "a4+"]
    found = {}
    for nm in names:
        try:
            H = np.stack(group_elements(named_symmetry(nm), 20000))
        except Exception:
            continue
        if not GK <= {tuple(np.round(h, 6).ravel()) for h in H} or len(H) == len(G):
            continue
        for h in H:
            if tuple(np.round(h, 6).ravel()) in GK:
                continue
            w, V = np.linalg.eig(h)
            F1 = np.real(V[:, np.abs(w - 1) < 1e-8])
            if F1.shape[1] != 2:
                continue
            Fx = np.linalg.svd(F1.T)[2][:2]
            key = tuple(np.round(Fx.T @ Fx, 6).ravel())
            if key in found:
                continue
            for a, b in arcs(Fx):
                mid = np.cos((a + b) / 2) * Fx[0] + np.sin((a + b) / 2) * Fx[1]
                K = closure(list(G[:6]) + [h] + list(G))
                if K is None:
                    continue
                n = orbit_size(K, mid)
                if n == 48:
                    ends = [nz.beta(np.cos(t) * Fx[0] + np.sin(t) * Fx[1]) for t in (a, b)]
                    ends = [e / e.sum() for e in ends]
                    found[key] = {"group": nm, "from": ends[0].tolist(), "to": ends[1].tolist(),
                                  "symmetry": len(K), "order_of_h": next(m for m in range(1, 50) if np.allclose(np.linalg.matrix_power(h, m), np.eye(4), atol=1e-7))}
                    print(f"{nm}: line {np.round(ends[0], 5).tolist()} -> {np.round(ends[1], 5).tolist()}, symmetry {len(K)}", flush=True)
                else:
                    found.setdefault(key, None)
    json.dump({"_about": __doc__.strip().split("\n\n")[0], "lines": [v for v in found.values() if v]}, open(OUT, "w"), indent=1)


if __name__ == "__main__":
    main()
